// Development generator: node tools/generate-assets.mjs
// Embeds canonical skill/**/*.md into paseo-hg-mem/server/skill-assets.ts.
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const skillDir = path.join(root, "skill");
const out = path.join(root, "paseo-hg-mem/server/skill-assets.ts");

function walk(dir, base = "") {
  return readdirSync(dir).sort().flatMap((n) => {
    const p = path.join(dir, n), rel = base ? `${base}/${n}` : n;
    return statSync(p).isDirectory() ? walk(p, rel) : rel.endsWith(".md") ? [rel] : [];
  });
}
const files = walk(skillDir).map((rel) => [rel, readFileSync(path.join(skillDir, rel), "utf8")]);
files.sort((a, b) => (a[0] < b[0] ? -1 : 1));
const sha = (s) => createHash("sha256").update(s, "utf8").digest("hex");
let ts = `// GENERATED by tools/generate-assets.mjs - do not edit by hand.\n`
  + `// Embedded text skill assets: relative path -> exact file content (UTF-8). ${files.length} files.\n`
  + `// Source: skill/**/*.md.\n\n`
  + `export const SKILL_ASSETS: Readonly<Record<string, string>> = {\n`;
for (const [rel, text] of files) ts += `  ${JSON.stringify(rel)}: ${JSON.stringify(text)},\n`;
ts += `};\n\n/** sha256 (hex) of each asset's UTF-8 bytes, for install verification. */\nexport const SKILL_ASSET_SHA256: Readonly<Record<string, string>> = {\n`;
for (const [rel, text] of files) ts += `  ${JSON.stringify(rel)}: ${JSON.stringify(sha(text))},\n`;
ts += `};\n`;
// Frozen pre-normalization releases, including the reviewed 2026-10-23 host install.
const legacy = JSON.parse(readFileSync(path.join(here, 'legacy-skill-sha256.json'), 'utf8'));
ts += `\n/** Recognized legacy bytes only; never infer ownership from a folder name. */\nexport const LEGACY_SKILL_SHA256: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(legacy, null, 2)};\n`;
writeFileSync(out, ts);
console.log(`wrote ${out}: ${files.length} assets, ${ts.length} chars`);
