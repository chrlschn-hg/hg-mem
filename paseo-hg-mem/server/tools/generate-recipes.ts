/// <reference types="node" />
// Development-only generator: embeds the hg-mem skill recipes into server/generated/recipes.ts.
// Runtime code never reads ../skill; this file is run by hand after recipe edits:
//   npx tsx server/tools/generate-recipes.ts
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const skillRoot = join(here, '..', '..', '..', 'skill');
const outFile = join(here, '..', 'generated', 'recipes.ts');

// Recipe name -> raw skill Markdown file. Every name must resolve to exactly one file.
export const RECIPE_FILES = {
  bootstrap: 'hg-mem-init/references/bootstrap.md',
  eligible: 'hg-mem/references/eligible.md',
  begin: 'hg-mem-write/references/begin.md',
  context: 'hg-mem-write/references/context.md',
  create: 'hg-mem-write/references/create.md',
  retire: 'hg-mem-write/references/retire.md',
  commit: 'hg-mem-write/references/commit.md',
  search: 'hg-mem-recall/references/search.md',
  directives: 'hg-mem-recall/references/directives.md',
  navigate: 'hg-mem-recall/references/navigate.md',
  explore: 'hg-mem-recall/references/explore.md',
  verify: 'hg-mem-maintain/references/verify.md',
} as const;
export type RecipeName = keyof typeof RECIPE_FILES;

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : name.endsWith('.md') ? [path] : [];
  });
}

// Same extraction rule as hgblock in skill/hg-mem/references/runtime.md: every ```sql fence, in order.
export function extractSql(markdown: string): string {
  const blocks: string[] = [];
  let inside = false;
  let current: string[] = [];
  for (const line of markdown.split('\n')) {
    if (!inside && line === '```sql') { inside = true; current = []; continue; }
    if (inside && line === '```') { inside = false; blocks.push(current.join('\n')); continue; }
    if (inside) current.push(line);
  }
  if (inside) throw new Error('unterminated ```sql fence');
  return blocks.join('\n');
}

export function generate(root: string): string {
  const skillMarkdown: Record<string, string> = {};
  for (const file of walk(root).sort()) {
    skillMarkdown[relative(root, file)] = readFileSync(file, 'utf8');
  }
  const recipes: Record<string, string> = {};
  for (const [name, file] of Object.entries(RECIPE_FILES)) {
    const markdown = skillMarkdown[file];
    if (markdown === undefined) throw new Error(`missing recipe file: ${file}`);
    const sql = extractSql(markdown);
    if (sql.trim() === '') throw new Error(`no sql block in ${file}`);
    recipes[name] = sql;
  }
  const lines = [
    '// Generated by server/tools/generate-recipes.ts from skill/**/*.md. Do not edit by hand.',
    `export const SKILL_MARKDOWN: Readonly<Record<string, string>> = ${JSON.stringify(skillMarkdown, null, 2)} as const;`,
    `export const RECIPE_SQL: Readonly<Record<${Object.keys(RECIPE_FILES).map((n) => `'${n}'`).join(' | ')}, string>> = ${JSON.stringify(recipes, null, 2)} as const;`,
    '',
  ];
  return lines.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(outFile, generate(skillRoot));
  console.log(`wrote ${relative(join(here, '..', '..'), outFile)}`);
}
